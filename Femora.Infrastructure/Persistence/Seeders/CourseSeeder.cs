        internal static string BuildVideoTranscript(string categoryName, string courseTitle, string courseDescription, int moduleStageIndex)
        {
            if (CategoryContentData.TryGetValue(categoryName, out var content) &&
                moduleStageIndex >= 0 && moduleStageIndex < content.VideoTranscripts.Length)
            {
                return $"(من كورس \"{courseTitle}\") {content.VideoTranscripts[moduleStageIndex]}";
            }

            // Fallback for any category not in the dictionary above - still better than
            // the old one-line boilerplate since it at least states real stage context.
            return $"مقدمة عن {courseTitle} ({categoryName}): {courseDescription} " +
                   "في هذا الدرس هنستعرض الأدوات والخامات الأساسية والخطوة الأولى للبدء عمليًا.";
        }

        public static async Task SeedAsync(AppDbContext context, UserManager<ApplicationUser> userManager,
            IConfiguration configuration, ILessonIndexingRepository lessonIndexingRepository)
        {
            // Get instructor users
            var instructorEmails = new[] { "instructor_1@test.com", "instructor_2@test.com", "multi_1@test.com", "multi_2@test.com" };
            var instructorUsers = new List<ApplicationUser>();

            foreach (var email in instructorEmails)
            {
                var user = await userManager.FindByEmailAsync(email);
                if (user != null)
                    instructorUsers.Add(user);
            }

            if (instructorUsers.Count == 0)
                return;

            int instructorIndex = 0;
            int courseCount = 0;
            int videoSeed = 0;
            int imageSeed = 1;

            // Iterate through each category and create courses
            foreach (var category in CoursesData.Keys)
            {
                var courseCategory = await context.CourseCategories
                    .FirstOrDefaultAsync(c => c.Name == category);

                if (courseCategory == null)
                    continue;

                var courseDataArray = CoursesData[category];

                foreach (var courseData in courseDataArray)
                {
                    try
                    {
                    var parts = courseData.Split('|');
                    var courseTitle = parts[0];
                    var courseDescription = parts[1];

                    // Check if course already exists
                    if (context.Courses.Any(c => c.Title == courseTitle))
                        continue;

                    var instructor = instructorUsers[instructorIndex % instructorUsers.Count];
                    var instructorProfile = await context.InstructorProfiles
                        .FirstOrDefaultAsync(p => p.UserId == instructor.Id);

                    if (instructorProfile == null)
                        continue;

                    var courseLevels = new[] { CourseLevel.Beginner, CourseLevel.Intermediate, CourseLevel.Advanced, CourseLevel.Expert };
                    var courseLevel = courseLevels[courseCount % courseLevels.Length];

                    // Create course
                    var course = new Course
                    {
                        InstructorProfileId = instructorProfile.Id,
                        Title = courseTitle,
                        Description = courseDescription,
                        ThumbnailUrl = null,
                        Price = (courseLevel == CourseLevel.Beginner) ? 29.99m : (courseLevel == CourseLevel.Intermediate) ? 49.99m : (courseLevel == CourseLevel.Advanced) ? 79.99m : 99.99m,
                        Category = courseCategory.Name,
                        Level = courseLevel,
                        Language = "العربية",
                        IsPublished = true,
                        RequiresApproval = false
                    };

                    // Assign image URLs for course (thumbnail + main image) using category keyword
                    if (CategoryImageKeywords.TryGetValue(courseCategory.Name, out var imgKeywords) && imgKeywords.Length > 0)
                    {
                        var kw = imgKeywords[courseCount % imgKeywords.Length];
                        course.ThumbnailUrl = BuildImageUrl(kw, imageSeed++, 640, 360);
                        course.ImageUrl = BuildImageUrl(kw, imageSeed++, 1280, 720);
                    }
                    else
                    {
                        course.ThumbnailUrl = BuildImageUrl("handmade,craft", imageSeed++, 640, 360);
                        course.ImageUrl = BuildImageUrl("handmade,craft", imageSeed++, 1280, 720);
                    }
                    context.Courses.Add(course);
                    await context.SaveChangesAsync();

                    // Create 3 modules per course
                    for (int moduleIndex = 0; moduleIndex < 3; moduleIndex++)
                    {
                        var module = new Module
                        {
                            CourseId = course.Id,
                            Title = $"{ModuleTitles[moduleIndex]}",
                            OrderIndex = moduleIndex + 1,
                            QuizId = Guid.Empty // Will be set after quiz creation
                        };
                        context.Modules.Add(module);
                    }
                    await context.SaveChangesAsync();

                    // Create lessons for each module
                    var modules = await context.Modules
                        .Where(m => m.CourseId == course.Id)
                        .OrderBy(m => m.OrderIndex)
                        .ToListAsync();

                    // درس فيديو واحد لكل درس، هنجهزه لفهرسة RAG بعد الحفظ
                    var videoLessonsToIndex = new List<(Guid LessonId, string Transcript)>();

                    foreach (var module in modules)
                    {
                        var lessonCount = 4 + (module.OrderIndex % 2); // 4-5 دروس لكل موديول

                        for (int lessonIdx = 0; lessonIdx < lessonCount; lessonIdx++)
                        {
                            if (lessonIdx == 0)
                            {
                                // ── الدرس الأول: فيديو قصير (دقيقة واحدة كحد أقصى) ──
                                var vIdx = videoSeed % VideoUrls.Length;
                                var videoLesson = new Lesson
                                {
                                    ModuleId = module.Id,
                                    Title = $"فيديو تعريفي: {module.Title}",
                                    Type = LessonType.Video,
                                    ContentUrl = VideoUrls[vIdx],
                                    ArticleContent = null,
                                    DurationSeconds = VideoDurationsSeconds[vIdx],
                                    OrderIndex = lessonIdx + 1,
                                    IsPreview = true
                                };
                                context.Lessons.Add(videoLesson);

                                var transcript = BuildVideoTranscript(category, courseTitle, courseDescription, module.OrderIndex - 1);
                                videoLessonsToIndex.Add((videoLesson.Id, transcript));

                                videoSeed++;
                            }
                            else
                            {
                                var titleIdx = (lessonIdx - 1) % LessonTitles.Length;
                                var articleContent = CategoryContentData.TryGetValue(category, out var content) && titleIdx < content.LessonArticles.Length
                                    ? content.LessonArticles[titleIdx]
                                    : $"محتوى درس \"{LessonTitles[titleIdx]}\" ضمن كورس {courseTitle}: {courseDescription}";

                                var lesson = new Lesson
                                {
                                    ModuleId = module.Id,
                                    Title = LessonTitles[titleIdx],
                                    Type = (LessonType)(2 + ((lessonIdx - 1) % 3)), // Article, Quiz, Assignment
                                    ContentUrl = null,
                                    ArticleContent = articleContent,
                                    DurationSeconds = 300 + (lessonIdx * 300),
                                    OrderIndex = lessonIdx + 1,
                                    IsPreview = false
                                };
                                context.Lessons.Add(lesson);
                            }
                        }
                    }
                    await context.SaveChangesAsync();

                    // ── فهرسة دروس الفيديو في السيرش إندكس لاختبار الـ RAG ──
                    // Each video is indexed independently now: previously a single failure here
                    // (very commonly an Azure OpenAI embedding rate limit, since this fires one
                    // call per video with zero delay across potentially dozens of courses) would
                    // throw out of the whole foreach and silently skip indexing for every other
                    // video lesson still queued for THIS course too - they'd exist in the DB with
                    // a real video but no LessonResource at all, and summarize would always fail
                    // with no way to tell why. Now each lesson's failure is caught and logged with
                    // its own lessonId, and a short delay between calls reduces how often the rate
                    // limit gets hit in the first place.
                    foreach (var (lessonId, transcript) in videoLessonsToIndex)
                    {
                        try
                        {
                            await lessonIndexingRepository.SeedIndexedContentAsync(lessonId, transcript);
                        }
                        catch (Exception ex)
                        {
                            Console.WriteLine($"[CourseSeeder] Failed to index video lesson {lessonId}: {ex.GetType().Name}: {ex.Message}");
                        }

                        await Task.Delay(300);
                    }

                    instructorIndex++;
                    courseCount++;
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"[CourseSeeder] Failed to seed course from category \"{category}\": {ex.GetType().Name}: {ex.Message}");
                        foreach (var entry in context.ChangeTracker.Entries().Where(e => e.State != EntityState.Unchanged).ToList())
                        {
                            entry.State = EntityState.Detached;
                        }
                    }
                }
            }
        }
    }
