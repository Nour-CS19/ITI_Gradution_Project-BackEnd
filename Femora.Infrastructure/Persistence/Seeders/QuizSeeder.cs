        public static async Task SeedAsync(AppDbContext context)
        {
            // Get all courses
            var courses = await context.Courses
                .Include(c => c.Modules)
                .ToListAsync();

            if (courses.Count == 0)
                return;

            foreach (var course in courses)
            {
                // Check if quiz already exists for this course
                if (context.Quizzes.Any(q => q.CourseId == course.Id))
                    continue;

                // Create course-level quiz
                var quiz = new Quiz
                {
                    CourseId = course.Id,
                    Title = $"{course.Title} - اختبار تقييمي",
                    MinimumPassingScore = 60,
                    MaxAttempts = 3
                };
                context.Quizzes.Add(quiz);
                await context.SaveChangesAsync();

                // Get questions for this course
                string[][] courseQuestions = null;
                if (QuizQuestions.TryGetValue(course.Title, out var questions))
                {
                    courseQuestions = questions;
                }

                // Add questions (use template data if available, or generic questions)
                for (int q = 0; q < 5; q++)
                {
                    string[] questionData;

                    if (courseQuestions != null && q < courseQuestions.Length)
                    {
                        questionData = courseQuestions[q];
                    }
                    else
                    {
                        // نموذج سؤال عام في حال عدم توفر أسئلة مخصصة لهذا الكورس
                        questionData = new[]
                        {
                            $"إيه المفهوم الأساسي في كورس {course.Title}؟",
                            "إتقان التقنية الصحيحة والممارسة المستمرة",
                            "اتباع التعليمات فقط",
                            "استخدام خامات غالية الثمن",
                            "الاستعجال في التنفيذ",
                            "0"
                        };
                    }

                    var question = new Question
                    {
                        QuizId = quiz.Id,
                        Text = questionData[0],
                        OrderIndex = q + 1
                    };
                    context.Questions.Add(question);
                    await context.SaveChangesAsync();

                    // Add 4 choices
                    for (int c = 0; c < 4; c++)
                    {
                        var choice = new Choice
                        {
                            QuestionId = question.Id,
                            Text = questionData[c + 1],
                            Order = c + 1,
                            IsCorrect = (c.ToString() == questionData[5])
                        };
                        context.Choices.Add(choice);
                    }
                }

                await context.SaveChangesAsync();
            }
        }
    }
